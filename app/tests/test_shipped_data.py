"""What the addon ships in its own data, and what it never does."""


def test_no_player_discoveries_ship_with_the_addon():
    # (the user, 2026-10-06: "my custom pins should not be included in shipped data, nor NPC discoveries or herbs or
    # ore. Those are up to the player to discover and share") nothing of theirs in the addon's own data.
    # NPCs since 2026-11-14 (the user's choice, "Ship all NPCs": every friendly NPC searchable from the start): the
    # game's own NPCs, from the CMaNGOS dump, in Data/Npcs.lua only (`agps npcs`), never the player's finds
    # (ns.db.npcs, ns.SharedNpcs); pins, herbs and ore still never.
    import re

    from azerothgps.paths import ADDON_DIR

    pins = (ADDON_DIR / "Data" / "Pins.lua").read_text(encoding="utf-8")
    body = re.search(r"ns\.SharedPins = \{(.*?)\n\}", pins, re.S)
    assert body is not None and body.group(1).strip() == "", "Data/Pins.lua ships pins"
    for f in (ADDON_DIR / "Data").glob("*.lua"):
        text = f.read_text(encoding="utf-8", errors="replace")
        for name in ("ns.SharedNodes", "ns.SharedNpcs", "ns.Npcs =", "ns.Herbs", "ns.Ores"):
            assert name not in text, f"{f.name} ships {name}"
        if f.name != "Npcs.lua":
            assert "ns.NpcsPacked" not in text, f"{f.name} ships NPCs: they go in Data/Npcs.lua only"
    npcs = (ADDON_DIR / "Data" / "Npcs.lua").read_text(encoding="utf-8")
    assert npcs.startswith("-- GENERATED by `agps npcs --write`"), "Data/Npcs.lua is made by `agps npcs` only"


def test_no_real_or_private_names_ship_with_the_addon():
    # (2026-11-05: three comments naming the user shipped in 1.1.9 and 1.1.10; the release zip is the whole addon
    # folder, comments included) no real names and none of the maintainers' private ones. The list is in the
    # maintainers' own copy only (app/azerothgps/community.py, the community repo's scrub): elsewhere this skips.
    import pytest

    community = pytest.importorskip("azerothgps.community")
    from azerothgps.paths import ADDON_DIR, REPO

    hits = []
    for f in sorted(ADDON_DIR.rglob("*")):
        if f.suffix.lower() not in (".lua", ".toc", ".txt", ".xml"):
            continue
        rel = f.relative_to(REPO).as_posix()
        hits += [f"{h.path}:{h.line}" for h in community.scan_text(rel, f.read_text(encoding="utf-8", errors="replace"))]
    assert not hits, "names that must not ship: " + ", ".join(hits[:20])
