def _search(ns, text, max=30):
    res = ns.GPS.SearchPlaces(text, max)
    return [res[i] for i in range(1, len(res) + 1)]


def _mobs(ns, text, max=30):
    return [e for e in _search(ns, text, max) if e.mob]


def test_a_mob_is_listed_once_at_its_camp_nearest_the_player(horde):
    lua, ns = horde
    (e,) = _mobs(ns, "Rattlecage Soldier")
    assert str(e.name) == "Rattlecage Soldier" and e.cont == 0 and e.yd is not None
    sp = ns.Layers.MobSpawns(e.mob)
    near = min(((sp[i + 1] - BRILL[0]) ** 2 + (sp[i + 2] - BRILL[1]) ** 2) ** 0.5
               for i in range(1, len(sp) + 1, 4) if sp[i] == 0)
    assert abs(e.yd - near) < 0.01 and e.yd < 1000
    assert str(e.tex) == "Interface\\TargetingFrame\\UI-TargetingFrame-Skull"
    assert str(e.sub).startswith("Enemy, ") and len(str(e.sub)) > 8, str(e.sub)  # ("Enemy, <place>")
    # part of a name: each mob of it once
    res = _mobs(ns, "rattlecage", 30)
    names = [str(e.name) for e in res]
    assert "Rattlecage Soldier" in names and len(names) == len(set(names))
    # not by the NPCs' generic words
    assert _mobs(ns, "repair") == [] and _mobs(ns, "vendor") == []


def test_never_the_nearest_on_another_continent_when_one_is_here(horde):
    lua, ns = horde
