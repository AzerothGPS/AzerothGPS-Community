"""Enemy mobs in the search (1.4.0, Kooki3z 2026-11-22: "for 1.4.0, I want to add all enemy mobs to the search
function, only showing the closest one in the list. If the mob level is orange or red to the player, show their level
range like (11-12) or (11) to the left of the enemies' name"). Data/Mobs.lua (`agps mobs`, mobs.py, the CMaNGOS dump
and Zephras Isle's snapshot): each mob once at its camp nearest the player (on the player's continent or island when
it has one there), the skull and "Enemy, <place>"; its levels before the name when orange or red; the option
searchEnemies; read at the first search, never at login, and only the listed mobs' spawns."""
import re
import time

import pytest

from azerothgps.paths import ADDON_DIR

MOBS = ADDON_DIR / "Data" / "Mobs.lua"
BRILL = (2254.0, 293.0, 0)
LINE = re.compile(r"^(\d+)\|([^|]+)\|(\d+)\|(\d+)\|([AHB])\|([0-4])\|(-?\d+( -?\d+)*(;-?\d+( -?\d+)*)*)$")


def _body():
    text = MOBS.read_text(encoding="utf-8")
    return text.split("ns.MobsPacked = [==[", 1)[1].split("]==]", 1)[0].strip().splitlines()


def test_the_data_file_is_one_packed_string_of_enemy_mobs():
    from azerothgps.mobs import read_spawns

    lines = _body()
    assert 1500 < len(lines) < 5000
    assert MOBS.stat().st_size < 1024 * 1024  # (a couple of MB at most: read at the first search)
    names, levels, ranks = {}, set(), {}
    for line in lines:
        m = LINE.match(line)
        assert m, line[:120]
        assert int(m.group(3)) <= int(m.group(4)), line[:80]
        names[m.group(2)] = (int(m.group(3)), int(m.group(4)), m.group(5))
        ranks[m.group(2)] = int(m.group(6))
        for lv, *_ in read_spawns(m.group(7)):
            levels.add(lv)
    assert len(names) == len(lines)  # (a name once)
    assert levels == {0, 1, 2991, 10001}  # (the continents, Zephras Isle, Undercity's Apothecarium; no dungeons)
    assert names["Hogger"] == (11, 11, "B") and names["Kobold Vermin"][2] == "B"
    # (each mob's rank, item 91: creature_template's; Razorfen Downs' quilboar outside are elites)
    assert ranks["Kobold Vermin"] == 0 and ranks["Razorfen Battleguard"] == 1
    assert names["Prideclaw"][:2] == (5, 6)  # (Zephras Isle's)
    # not mobs: the friendly NPCs, the other faction's guards and townsfolk
    for npc in ("Innkeeper Renee", "Innkeeper Farley", "Stormwind City Guard", "Orgrimmar Grunt", "Thrall"):
        assert npc not in names, npc
    # read only by the search: Layers' L.ShippedMobs
    readers = sorted(f.name for f in ADDON_DIR.rglob("*.lua")
                     if "MobsPacked" in f.read_text(encoding="utf-8", errors="replace"))
    assert readers == ["Layers.lua", "Mobs.lua"]
    assert MOBS.read_text(encoding="utf-8").startswith("-- GENERATED by `agps mobs --write`")


def test_the_generator_packs_camps_delta_coded():
    from azerothgps.mobs import camps, lua_text, mob_side, read_spawns, spawns_text

    alliance = {"Faction": 1, "FactionGroup": 3, "FriendGroup": 2, "EnemyGroup": 12, "Enemies": [0], "Friend": [0]}
    horde = {"Faction": 2, "FactionGroup": 5, "FriendGroup": 4, "EnemyGroup": 10, "Enemies": [0], "Friend": [0]}
    sw = {"Faction": 72, "FactionGroup": 3, "FriendGroup": 2, "EnemyGroup": 12, "Enemies": [0], "Friend": [0]}
    monster = {"Faction": 14, "FactionGroup": 8, "FriendGroup": 0, "EnemyGroup": 1, "Enemies": [0], "Friend": [0]}
    boar = {"Faction": 7, "FactionGroup": 0, "FriendGroup": 0, "EnemyGroup": 0, "Enemies": [0], "Friend": [0]}
    # (a monster: both sides'; an Alliance town's guard is no mob, nor a neutral boar)
    assert [mob_side(f, alliance, horde) for f in (monster, sw, boar)] == ["B", None, None]
    spawns = [(0, 10.2, 20.0, 5.0), (0, 30.0, 20.0, 5.4), (0, 100.0, 50.0, 6.0), (1, -5.0, 7.0, -2.0)]
    assert camps(spawns, 25) == [spawns[0], spawns[2], spawns[3]]  # (one within 25 yd of one kept: that camp)
    text = spawns_text(camps(spawns, 25))
    assert text == "0 10 20 5 90 30 1;1 -5 7 -2"
    assert read_spawns(text) == [(0, 10, 20, 5), (0, 100, 50, 6), (1, -5, 7, -2)]
    lua = lua_text({"Ogre": {"id": 7, "name": "Ogre", "lo": 30, "hi": 31, "side": "B", "spawns": spawns}})
    assert "\n7|Ogre|30|31|B|0|0 10 20 5 90 30 1;1 -5 7 -2\n" in lua
    lua = lua_text({"Ogre": {"id": 7, "name": "Ogre", "lo": 30, "hi": 31, "side": "B", "rank": 1, "spawns": spawns}})
    assert "\n7|Ogre|30|31|B|1|0 10 20 5 90 30 1;1 -5 7 -2\n" in lua


