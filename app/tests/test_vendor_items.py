"""What the vendors sell, searchable (asked 2026-11-15, a Horde hunter's screenshot: Quick Find's Arrows sent him to a
Bow Merchant 920 yd away, Trak'gen, a General Goods Merchant right by him in Orgrimmar, selling Sharp Arrow: "need to
search for all vendors items for sell to do this correctly. Should also do this for all items so they can be searched
like "arrows" or "sharp arrow" should send me to the closest vendor that sells them"; the user chose "Both": lists
shipped from data, and each vendor's real stock learned in game when its window opens, the learned list winning).
Data/VendorItems.lua (`agps vendors`, vendors.py, the CMaNGOS dump's npc_vendor / npc_vendor_template / item_template);
an item's name or its start lists its sellers nearest first ("Sells Sharp Arrow, Orgrimmar" in grey), with what and
where typed together too; "arrows", "bullets", "ammo" (and Quick Find's) by what vendors stock; the player's faction's
and neutral vendors only."""
