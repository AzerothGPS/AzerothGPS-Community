TRAKGEN = 3313  # (General Goods Merchant, Orgrimmar: sells Sharp Arrow)
SHARP_ARROW, ROUGH_ARROW, LIGHT_SHOT, WATER = 2515, 2512, 2516, 159


def _body():
    text = ITEMS.read_text(encoding="utf-8")
    return text.split("ns.VendorItemsPacked = [==[", 1)[1].split("]==]", 1)[0].strip().splitlines()


def test_the_data_file_is_one_packed_string_of_the_shipped_vendors_lists():
    text = ITEMS.read_text(encoding="utf-8")
    assert text.startswith("-- GENERATED by `agps vendors --write`") and "Do not edit by hand" in text
    assert ITEMS.stat().st_size < 100 * 1024  # (CurseForge size: read at the first search)
    lines = _body()
    cut = lines.index("#")
    items = {}
    for line in lines[:cut]:
        m = re.match(r"^(\d+)\|([ab]?)\|([^|]+)$", line)
        assert m, line
        items[int(m.group(1))] = (m.group(2), m.group(3))
    order = sorted(items)
    vendors = {}
    for line in lines[cut + 1:]:
        m = re.match(r"^(\d+)\|(=\d+|[0-9a-z]+(?:,[0-9a-z]+)*)$", line)
        assert m, line
        rest = m.group(2)
        vendors[int(m.group(1))] = vendors[int(rest[1:])] if rest.startswith("=") else \
            [order[int(k, 36)] for k in rest.split(",")]
    assert 500 < len(vendors) < 2000 and 1000 < len(items) < 3000
    assert items[SHARP_ARROW] == ("a", "Sharp Arrow") and items[LIGHT_SHOT] == ("b", "Light Shot")
    assert SHARP_ARROW in vendors[TRAKGEN] and LIGHT_SHOT in vendors[TRAKGEN]
    # only the NPCs Data/Npcs.lua ships
    from azerothgps.vendors import shipped_npc_ids
    assert set(vendors) <= shipped_npc_ids()
    # loaded after Data/Npcs.lua, read only by Layers' L.VendorItems
    toc = (ADDON_DIR / "AzerothGPS.toc").read_text(encoding="utf-8").splitlines()
    assert toc.index("Data\\VendorItems.lua") == toc.index("Data\\Npcs.lua") + 1
    readers = sorted(f.name for f in ADDON_DIR.rglob("*.lua")
                     if "VendorItemsPacked" in f.read_text(encoding="utf-8", errors="replace"))
    assert readers == ["Layers.lua", "VendorItems.lua"]


def _table(name, cols, rows):
    head = "CREATE TABLE `%s` (\n%s\n) ENGINE=MyISAM;\n" % (name, ",\n".join(f"  `{c}` int" for c in cols))
    vals = ",".join("(" + ",".join(repr(v) if isinstance(v, str) else str(v) for v in r) + ")" for r in rows)
    return head + f"INSERT INTO `{name}` VALUES {vals};\n"


def test_the_generator_on_a_tiny_dump(tmp_path):
    from azerothgps.hostile import DUMP
    from azerothgps.vendors import build, lua_text

    sql = "".join((
        _table("creature_template", ["Entry", "VendorTemplateId"], [(1, 0), (2, 50), (3, 0), (4, 0), (5, 0)]),
        _table("npc_vendor", ["entry", "item", "maxcount", "incrtime", "slot", "condition_id", "comments"],
               [(1, 10, 0, 0, 0, 0, "a"), (1, 11, 0, 0, 0, 0, "b"), (1, 99, 0, 0, 0, 0, "unknown item"),
                (2, 11, 0, 0, 0, 0, "c"), (3, 10, 0, 0, 0, 0, "d"), (3, 11, 0, 0, 0, 0, "e"),
                (4, 13, 0, 0, 0, 0, "not shipped")]),
        _table("npc_vendor_template", ["entry", "item", "maxcount", "incrtime", "slot", "condition_id", "comments"],
               [(50, 12, 0, 0, 0, 0, "f")]),
        _table("item_template", ["entry", "class", "subclass", "name"],
               [(10, 6, 2, "Sharp Arrow"), (11, 0, 0, "Ice Cold Milk"), (12, 6, 3, "Light Shot"),
                (13, 2, 2, "A Bow")]),
    ))
    dump = tmp_path / DUMP
    dump.parent.mkdir(parents=True)
    with gzip.open(dump, "wt", encoding="utf-8") as f:
        f.write(sql)
    items, sells = build(tmp_path, {1, 2, 3, 5})
    assert sells == {1: [10, 11], 2: [11, 12], 3: [10, 11]}  # (99 unknown; 4 not shipped; 5 sells nothing)
    assert items == {10: ("a", "Sharp Arrow"), 11: ("", "Ice Cold Milk"), 12: ("b", "Light Shot")}
    text = lua_text(items, sells)
    assert text.startswith("-- GENERATED by `agps vendors --write`")
    body = text.split("[==[\n", 1)[1].split("]==]", 1)[0].splitlines()
    assert body == ["10|a|Sharp Arrow", "11||Ice Cold Milk", "12|b|Light Shot", "#", "1|0,1", "2|1,2", "3|=1"]
    # the addon reads it back as written
    from lupa import lua51
    lua = lua51.LuaRuntime()
    ns = lua.table()
    lua.eval("function(src, ns) assert(loadstring(src))('AzerothGPS', ns) end")(text, ns)
    assert "Sharp Arrow" in str(ns.VendorItemsPacked)


