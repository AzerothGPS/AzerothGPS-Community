def _at(lua, x, y, cont):
    lua.execute(f"AGPS_POS = {{ {x}, {y}, {cont} }}")


def _search(ns, text, max=10):
    res = ns.GPS.SearchPlaces(text, max)
    return [res[i] for i in range(1, len(res) + 1)]


def _names(ns, text, max=10):
    return [str(e.name) for e in _search(ns, text, max) if e.npc]


def _merchant(lua, ns, npc_id, name, stock, faction="Horde", link=False):
    """The player opens NPC `npc_id`'s vendor window listing `stock` [(item id, name, projectile subclass or None)];
    `link`: the client gives the items' links only (no GetMerchantItemID)."""
    rows = ", ".join("{ %d, %s, %s }" % (i, f'"{n}"' if n else "nil", s if s is not None else "nil")
                     for i, n, s in stock)
    lua.execute(f"""
      AGPS_OLDM = {{ guid = UnitGUID, name = UnitName, fac = UnitFactionGroup }}
      AGPS_STOCK = {{ {rows} }}
      UnitGUID = function(u) if u == "npc" then return "Creature-0-1-2-3-{npc_id}-00000ABC" end return AGPS_OLDM.guid(u) end
      UnitName = function(u) if u == "npc" then return "{name}" end return AGPS_OLDM.name(u) end
      UnitFactionGroup = function(u) if u == "npc" then return "{faction}" end return AGPS_OLDM.fac(u) end
      GetMerchantNumItems = function() return #AGPS_STOCK end
      GetMerchantItemID = {"nil" if link else "function(i) return AGPS_STOCK[i][1] end"}
      GetMerchantItemLink = function(i) return "|cffffffff|Hitem:" .. AGPS_STOCK[i][1] .. "::::::::|h[x]|h|r" end
      GetMerchantItemInfo = function(i) return AGPS_STOCK[i][2] end
      GetItemInfoInstant = function(id)
        for _, s in ipairs(AGPS_STOCK) do
          if s[1] == id and s[3] then return id, "Projectile", "", "", 0, 6, s[3] end
        end
        return id, "Misc", "", "", 0, 15, 0
      end
    """)
    try:
        ns.Layers.OnNpcWindow("MERCHANT_SHOW")
    finally:
        lua.execute("UnitGUID, UnitName, UnitFactionGroup = AGPS_OLDM.guid, AGPS_OLDM.name, AGPS_OLDM.fac "
                    "GetMerchantNumItems, GetMerchantItemID, GetMerchantItemLink, GetMerchantItemInfo = nil, nil, nil, nil "
                    "GetItemInfoInstant, AGPS_OLDM, AGPS_STOCK = nil, nil, nil")


def _by(ns, npc_id):
    """The player stood by shipped NPC `npc_id` (its first spawn)."""
    n = ns.Layers.ShippedNpcs()[1][npc_id]
    return n.spawns[2], n.spawns[3], n.spawns[1]


def test_sharp_arrow_from_the_valley_of_strength_finds_trakgen_first(horde):
    lua, ns = horde
    for text in ("sharp arrow", "Sharp Ar", "SHARP ARROW", " sharp  arrow "):
        res = _search(ns, text)
        assert res and str(res[0].name) == "Trak'gen", (text, [str(e.name) for e in res])
        assert str(res[0].sub) == "Sells Sharp Arrow, Orgrimmar", str(res[0].sub)
        yds = [e.yd for e in res if e.npc and e.yd is not None]
        assert yds == sorted(yds), text  # (nearest first)
    milk = _search(ns, "ice cold milk")
    assert milk and all("Sells Ice Cold Milk" in str(e.sub) for e in milk if e.npc)
    assert "Trak'gen" in [str(e.name) for e in milk]
    # what and where typed together
    org = _search(ns, "sharp arrow orgrimmar")
    assert str(org[0].name) == "Trak'gen" and all("Orgrimmar" in str(e.sub) for e in org[:4])
    rh = _search(ns, "sharp arrow razor hill")
    assert rh and "Razor Hill" in str(rh[0].sub) and "Sells Sharp Arrow" in str(rh[0].sub), [str(e.sub) for e in rh]
    # two letters aren't an item
    assert not [e for e in _search(ns, "sh") if e.sells]


def test_arrows_bullets_and_ammo_count_general_goods_sellers(horde):
    lua, ns = horde
    G = ns.GPS
    arrows = _search(ns, "arrows")
    assert str(arrows[0].name) == "Trak'gen" and "General Goods" in str(arrows[0].title)
    assert "Trak'gen" in _names(ns, "bullets") and "Trak'gen" in _names(ns, "ammo")
    # Kaja (Guns and Ammo) sells no arrows
    assert "Kaja" not in _names(ns, "arrows", 30) and "Kaja" in _names(ns, "bullets")
    # Quick Find's Arrows: Trak'gen, not the Bow Merchant further off
    lua.execute("AGPS_QF_UC = UnitClass UnitClass = function() return 'Hunter', 'HUNTER' end")
    try:
        e = G.QuickFindClick(next(q for q in G.QUICK_FIND.values() if str(q.kind) == "ammo").sub[1])
        assert str(e.name) == "Trak'gen", str(e.name)
    finally:
        lua.execute("UnitClass = AGPS_QF_UC")
        ns.Nav.Clear()
    # the title's words still where nothing's known of a vendor's stock: one talked to that's not in the data
    lua.execute(f"AGPS_POS = {{ {VALLEY_OF_STRENGTH[0] + 20}, {VALLEY_OF_STRENGTH[1]}, 1 }}")
    ns.Layers.NoteNpc(990001, "Test Bowyer", "Bowyer", 1, VALLEY_OF_STRENGTH[0] + 20, VALLEY_OF_STRENGTH[1], "Orgrimmar")
    assert "Test Bowyer" in _names(ns, "arrows", 30)


def test_a_learned_stock_overrides_the_shipped_list_and_is_kept(horde):
    lua, ns = horde
    x, y, lv = _by(ns, TRAKGEN)
    _at(lua, x, y, lv)
    _merchant(lua, ns, TRAKGEN, "Trak'gen", [(LIGHT_SHOT, "Light Shot", 3), (WATER, "Refreshing Spring Water", None)])
    sells = ns.db.npcs[TRAKGEN].sells
    assert sorted(sells.keys()) == [WATER, LIGHT_SHOT] and str(sells[LIGHT_SHOT].name) == "Light Shot"
    assert sells[LIGHT_SHOT].kind == "b" and sells[WATER].kind is None
    _at(lua, *VALLEY_OF_STRENGTH)
    # the learned list wins: no Sharp Arrow, no arrows; Light Shot and bullets
    assert "Trak'gen" not in _names(ns, "sharp arrow", 30) and "Asoran" in _names(ns, "sharp arrow", 30)
    assert "Trak'gen" not in _names(ns, "arrows", 30) and "Trak'gen" in _names(ns, "bullets", 30)
    shot = _search(ns, "light shot")
    assert str(shot[0].name) == "Trak'gen" or "Trak'gen" in [str(e.name) for e in shot]
    assert all("Sells Light Shot" in str(e.sub) for e in shot if str(e.name) == "Trak'gen")
    # opened again, an item more (by its link, the client's older API): added, the others kept (keep data forever)
    _at(lua, x, y, lv)
    _merchant(lua, ns, TRAKGEN, "Trak'gen", [(ROUGH_ARROW, "Rough Arrow", 2)], link=True)
    assert sorted(ns.db.npcs[TRAKGEN].sells.keys()) == [WATER, ROUGH_ARROW, LIGHT_SHOT]
    _at(lua, *VALLEY_OF_STRENGTH)
    assert "Trak'gen" in _names(ns, "arrows", 30) and "Trak'gen" in _names(ns, "rough arrow", 30)
    assert not ns.Layers.NoteMerchantItems(TRAKGEN)  # (no vendor window open: nothing)
    # a vendor the data doesn't have, its stock learned: found by its items
    px, py = VALLEY_OF_STRENGTH[0] + 15, VALLEY_OF_STRENGTH[1] + 5
    _at(lua, px, py, 1)
    _merchant(lua, ns, 990002, "Test Peddler", [(990003, "Zz Test Bolt", 2)])
    _at(lua, *VALLEY_OF_STRENGTH)
    res = _search(ns, "zz test")
    assert res and str(res[0].name) == "Test Peddler" and str(res[0].sub).startswith("Sells Zz Test Bolt")
    assert "Test Peddler" in _names(ns, "arrows", 30)


def test_an_enemy_faction_vendor_is_never_listed(horde):
    lua, ns = horde
    shipped = [e for e in _search(ns, "sharp arrow", 300) if e.shipped]
    assert len(shipped) > 10 and all(str(e.shipped.side) in ("H", "B") for e in shipped)
    assert all(str(e.shipped.side) in ("H", "B") for e in _search(ns, "arrows", 300) if e.shipped)
    # a vendor of the other faction talked to on this account (another character): its stock never listed
    px, py = VALLEY_OF_STRENGTH[0] + 10, VALLEY_OF_STRENGTH[1]
    _at(lua, px, py, 1)
    _merchant(lua, ns, 990004, "Test Alliance Grocer", [(990005, "Zz Enemy Bread", None)], faction="Alliance")
    _at(lua, *VALLEY_OF_STRENGTH)
    assert "Test Alliance Grocer" not in _names(ns, "zz enemy bread")
    # an Alliance player isn't sent to Trak'gen
    ns.CharDB().faction = "Alliance"
    _at(lua, *BRILL)
    found = [e for e in _search(ns, "sharp arrow", 300) if e.shipped]
    assert found and "Trak'gen" not in [str(e.name) for e in found]
    assert all(str(e.shipped.side) in ("A", "B") for e in found)
