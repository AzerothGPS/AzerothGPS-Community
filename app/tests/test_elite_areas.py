def _areas():
    out, cont = {}, None
    for line in ELITES.read_text(encoding="utf-8").splitlines():
        m = re.match(r"\s*\[(\d+)\] = \{$", line)
        if m:
            cont = int(m.group(1))
            out[cont] = []
            continue
        m = re.match(r'\s*\{ (\d+), (\d+), "([AHB])", \{ ([-\d,]+) \} \},$', line)
        if m:
            v = [int(x) for x in m.group(4).split(",")]
            out[cont].append((int(m.group(1)), int(m.group(2)), m.group(3), list(zip(v[0::3], v[1::3], v[2::3]))))
    return out


def test_the_data_file_has_the_elite_areas_with_their_levels():
    text = ELITES.read_text(encoding="utf-8")
    assert text.startswith("-- GENERATED by `agps mobs --write`")
    toc = (ADDON_DIR / "AzerothGPS.toc").read_text(encoding="utf-8")
    assert toc.index("Data\\Elites.lua") < toc.index("Router.lua")
    areas = _areas()
    assert set(areas) == {0, 1} and 30 < len(areas[0]) < 150 and 30 < len(areas[1]) < 150
    assert ELITES.stat().st_size < 200 * 1024
    for list_ in areas.values():
        for lo, hi, side, circles in list_:
            assert 1 <= lo <= hi <= 63 and circles and all(20 <= r <= 50 for _, _, r in circles)
    # (Razorfen Downs' quilboar outside: one area, 33 to 36)
    (rfd,) = [a for a in areas[1] if any(abs(x - RFD[0]) < 60 and abs(y - RFD[1]) < 60 for x, y, _ in a[3])]
    assert rfd[:3] == (33, 36, "B") and len(rfd[3]) > 20


def test_the_generator_clusters_elites_into_areas():
    from azerothgps.mobs import AREA_GAP_YD, ELITE_YD, elite_areas, elites_lua

    camp = [(1, 100.0 + 15 * i, 200.0, 30, 32, "B", 0.0) for i in range(4)]
    near = [(1, 100.0 + 45 + 2 * ELITE_YD + AREA_GAP_YD - 1, 200.0, 34, 34, "B", 5.0)]  # (within the gap: the same area)
    lone = [(1, 2000.0, 2000.0, 50, 50, "B", 0.0), (1, 2010.0, 2000.0, 50, 50, "B", 0.0)]  # (two: no area)
    theirs = [(0, 0.0, 0.0, 20, 21, "A", 0.0)] * 3  # (the Alliance's enemies only: an area of its own side)
    areas = elite_areas(camp + near + lone + theirs)
    assert sorted(areas) == [0, 1]
    (a,) = areas[1]
    assert (a["lo"], a["hi"], a["side"], a["n"]) == (30, 34, "B", 5)
    (b,) = areas[0]
    assert b["side"] == "A" and b["circles"] == [(0, 0, round(ELITE_YD + 5))]
    lua = elites_lua(areas)
    assert '[1] = {\n    { 30, 34, "B", { ' in lua and "ns.EliteAreas = {" in lua


def _hit(v):
    return (v[0] if isinstance(v, tuple) else v) is True


def _horde(lua, ns, level):
    lua.execute(f"UnitFactionGroup = function() return 'Horde' end; AGPS_LEVEL = {level}")
    ns.CharDB().faction = "Horde"


@pytest.fixture
def horde(game):  # noqa: F811
    lua, ns = game
    st = ns.settings.gps
    lua.execute("AGPS_E_UFG = UnitFactionGroup AGPS_E_POS = AGPS_POS AGPS_E_LVL = AGPS_LEVEL")
    saved = (ns.CharDB().faction, st.avoidElites, st.eliteOffset, st.avoidHostile, st.showAvoided, st.useFlights)
    st.useFlights = False
    yield lua, ns
    ns.Nav.Clear()
    ns.Nav.route = None
    (ns.CharDB().faction, st.avoidElites, st.eliteOffset, st.avoidHostile, st.showAvoided, st.useFlights) = saved
    lua.execute("UnitFactionGroup = AGPS_E_UFG AGPS_POS = AGPS_E_POS AGPS_LEVEL = AGPS_E_LVL")
    ns.Router.Reset()


def test_an_area_is_avoided_from_the_players_level_plus_the_slider(horde):
    lua, ns = horde
    R, st = ns.Router, ns.settings.gps
    st.avoidElites, st.eliteOffset, st.avoidHostile = None, None, None  # (the defaults: on, -10)
    assert ns.DEFAULTS.gps.avoidElites is True and ns.DEFAULTS.gps.eliteOffset == -10 and R.EliteOffset() == -10

    def avoided():
        return _hit(R.HostileAt(1, RFD[0], RFD[1]))

    _horde(lua, ns, 45)  # (45 - 10 = 35: elites 35 and up, Razorfen Downs' 36 among them)
    assert R.EliteMin() == 36 and str(R.HostileSide()) == "H+36" and avoided()
    _horde(lua, ns, 60)  # (60 - 10 = 50: Razorfen Downs' ignored, routed through as normal)
    assert R.EliteMin() >= 50 and not avoided()
    st.eliteOffset = -20  # (55 - 20 = 35)
    _horde(lua, ns, 55)
    assert avoided()
    st.eliteOffset = 5  # (35 + 5 = 40: none of Razorfen Downs')
    _horde(lua, ns, 35)
    assert not avoided()
    st.eliteOffset = -99  # (out of range: its end, -20)
    assert R.EliteOffset() == -20
    st.eliteOffset = None
    _horde(lua, ns, 45)
    st.avoidElites = False
    assert R.EliteMin() is None and not avoided() and str(R.HostileSide()) == "H"
    st.avoidHostile = False  # (neither avoided: no key at all, as before)
    assert R.HostileSide() is None
    st.avoidElites = None
    assert str(R.HostileSide()) == "~H+36" and avoided()  # (the elites still avoided, the guards not)
    assert R.HOSTILE_LIGHT[R.HostileSide()] is None and R.HOSTILE_LIGHT["H+36"] == "h"


def test_the_guards_are_as_before_with_the_elites_added(horde):
    """1.4.0's guard avoidance works well (Kooki3z, after slower trips): the guards' circles, towns and reach are the
    same with the elite areas added after them."""
    lua, ns = horde
    R = ns.Router
    _horde(lua, ns, 45)
    for cont in (0, 1):
        raw = ns.Hostile[cont].H
        merged = ns.Hostile[cont][R.HostileSide()]
        assert merged.guardN == len(raw) and len(merged) > len(raw)
        assert all(merged[i] == raw[i] for i in range(1, len(raw) + 1))
        t1, t2 = R.HostileTowns(cont, "H"), R.HostileTowns(cont, R.HostileSide())
        assert all(t1[i] == t2[i] for i in range(1, len(raw) + 1, 3))
        # (each elite circle's town is its area's, never a guard town)
        assert all(t2[i] > len(raw) for i in range(len(raw) + 1, len(merged) + 1, 3))
    x, y = ASTRANAAR
    assert _hit(R.HostileAt(1, x, y))  # (the Alliance's sentinels, as ever)


def _route(lua, ns, a, b):
    N, R = ns.Nav, ns.Router
    N.Clear()
    lua.execute(f"AGPS_POS = {{ {a[0]}, {a[1]}, 1 }}")
    N.SetStops(lua.eval(f"{{ {{ x = {b[0]}, y = {b[1]}, cont = 1, name = 'stop' }} }}"), False, "red")
    N.Invalidate(True, True)
    R.WallsChanged()
    return N.Route(a[0], a[1], 1)


def _elite_yards(ns, r, key):
    R = ns.Router
    yd = 0.0
    for part in r.parts.values():
        pts = part.pts
        n = len(pts)
        if n < 4:
            continue
        exempt = R.HostileTownsNear(part.cont, key, pts[1], pts[2], pts[n - 1], pts[n])
        for i in range(1, n - 2, 2):
            yd += R.HostileYards(part.cont, pts[i], pts[i + 1], pts[i + 2], pts[i + 3], key, exempt)
    return yd


def test_darkcloud_to_camp_taurajo_goes_round_razorfen_downs_at_45_not_at_60(horde):
    lua, ns = horde
    st = ns.settings.gps
    st.avoidElites, st.eliteOffset = None, None
