def test_a_start_just_outside_its_elite_areas_reach_is_in_it(horde):
    """A start or stop within Router.ELITE_NEAR (60 yd) of an elite area's reach is in that area, its walk out not paid
    for (a town of the guards: TOWN_NEAR, 20 yd, as before)."""
    lua, ns = horde
    R = ns.Router
    st = ns.settings.gps
    st.avoidElites, st.eliteOffset = None, None
    _horde(lua, ns, 20)
    key = R.HostileSide()
    lst = ns.Hostile[1][key]
    i = lst.guardN + 1  # (an elite circle)
