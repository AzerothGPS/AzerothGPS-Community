"""The city route review: candidate routes compared with another way's walk, out to a review addon in game, and the
decisions made there back.

`agps route-review export` turns REVIEW (a JSON list, below) into REVIEW_FILE in every addon whose .toc lists it (the
same way the floor survey's list reaches its addon; `agps install-addon` refreshes it too). It's plain data: a Lua table,
every string quoted, every number checked. The addon shows each candidate, draws both lines on the map and keeps a
decision per candidate in its SavedVariables. `agps route-review import` reads those decisions (read only: the
SavedVariables are never written) into DECISIONS.

REVIEW, one entry per candidate:

    [{"id": "orgrimmar-1", "city": "Orgrimmar", "level": 1,          # level: the continent, or Undercity's 10001
      "start": {"x": .., "y": .., "z": .., "name": ".."}, "stop": {...},   # x north, y west (world yards), z the game's
      "agps": {"yd": N, "pts": [[x, y, z], ...]},                    # AzerothGPS's route
      "spf": {"yd": N, "pts": [[x, y, z], ...]},                     # the other way's walk
      "why": "one line"}]

x, y are AzerothGPS's world yards, the server's own (`.go xyz x y z map`); Undercity's level is drawn in its base
continent's coordinates. z is the game's height (as `.gps` gives it).

DECISIONS, by candidate id: "approve" or "reject" (plain strings), or for a corrected path an object
    {"decision": "correct", "tracks": [<recorded walk time>, ...], "yd": N, "level": L}
where `tracks` are the times (the keys) of the walks recorded with AzerothGPS's Record that replace that candidate's
route: they are in the client's AzerothGPS SavedVariables (`tracks`, marked `recorded`) and reach the road data the way
every recorded walk does. A decision is kept only while its candidate is the same one it was made on (`sig`: its start,
stop and both lengths); one made on an older list with the same id is left out and counted.
"""

from __future__ import annotations

import hashlib
import json
import math
import re
from pathlib import Path

from .paths import ADDON_DIR, data_dir

REVIEW_FILE = "RouteReview.lua"
REVIEW_DIR = data_dir() / "debug" / "city-spf"
REVIEW = REVIEW_DIR / "review.json"
DECISIONS = REVIEW_DIR / "decisions.json"
DECIDED = ("approve", "reject", "correct")


def review_addons(addons: Path) -> list[tuple[Path, str]]:
    """The addons in AddOns folder `addons` that load REVIEW_FILE: [(their folder, their saved variable)]."""
    from .interiorfloors import survey_addons
    return survey_addons(addons, REVIEW_FILE)


def load_review(path: Path = REVIEW) -> list:
    if not Path(path).exists():
        return []
    doc = json.loads(Path(path).read_text(encoding="utf-8"))
    if not isinstance(doc, list):
        raise ValueError(f"{path}: not a list of candidates")
    return doc


def base_maps(cities_lua: Path | None = None) -> dict:
    """{city level: the continent (map id) it's drawn on}, from Data/Cities.lua (Undercity's 10001: 0)."""
    path = cities_lua or ADDON_DIR / "Data" / "Cities.lua"
    if not Path(path).exists():
        return {}
    text = Path(path).read_text(encoding="utf-8")
    return {int(a): int(b) for a, b in re.findall(r"CityLevels\[(\d+)\]\s*=\s*\{\s*base\s*=\s*(\d+)", text)}


def map_of(level: int, bases: dict) -> int:
    """The map id `.go xyz` takes for a level: a dungeon's (20000 + MapID), a city level's base, else the level."""
    if level >= 20000:
        return level - 20000
    if level >= 10000:
        return bases.get(level, 0)
    return level


def sig_of(e: dict) -> str:
    """A short mark of what a candidate is (start, stop, both lengths): a decision counts only on the same one."""
    s, t = e["start"], e["stop"]
    key = "%.0f,%.0f,%.0f,%.0f,%d,%.0f,%.0f" % (float(s["x"]), float(s["y"]), float(t["x"]), float(t["y"]),
                                                int(e.get("level", 0)), float(e["agps"]["yd"]), float(e["spf"]["yd"]))
    return hashlib.sha1(key.encode()).hexdigest()[:10]


def _num(v) -> str:
    f = float(v)
    if not math.isfinite(f):
        raise ValueError(f"not a number: {v!r}")
    return f"{round(f, 1):g}"


def _str(v) -> str:
    s = re.sub(r"[\x00-\x1f\x7f]", " ", str(v if v is not None else ""))
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def review_lua(rows: list, bases: dict | None = None) -> str:
    """The candidates as Lua data: `ns.RouteReview`, one row each in the list's order; a line's points flat x, y."""
    bases = base_maps() if bases is None else bases
    out = ["-- GENERATED by `agps route-review export` from the city route review's list. Do not edit by hand.",
           "-- Each row: a route to check. start/stop = { x, y, z, name } (z the game's), map = the map id .go takes;",
           "-- agps/spf = { yd, pts = { x1, y1, x2, y2, ... } } in world yards (x north, y west).",
           "local _, ns = ...",
           "ns.RouteReview = {"]
    for e in rows:
        level = int(e.get("level", 0))

        def spot(p):
            return f"{{ x = {_num(p['x'])}, y = {_num(p['y'])}, z = {_num(p.get('z', 0))}, name = {_str(p.get('name', ''))} }}"

        def line(r):
            pts = ", ".join(f"{_num(p[0])}, {_num(p[1])}" for p in r.get("pts", []))
            return f"{{ yd = {_num(r.get('yd', 0))}, pts = {{ {pts} }} }}"
        out.append(f"  {{ id = {_str(e['id'])}, sig = {_str(sig_of(e))}, city = {_str(e.get('city', ''))}, "
                   f"level = {level}, map = {map_of(level, bases)},")
        out.append(f"    start = {spot(e['start'])}, stop = {spot(e['stop'])},")
        out.append(f"    agps = {line(e['agps'])},")
        out.append(f"    spf = {line(e['spf'])},")
        out.append(f"    why = {_str(e.get('why', ''))} }},")
    out.append("}")
    return "\n".join(out) + "\n"


def export_review(addons_dirs, rows: list | None = None, log=print) -> int:
    """Writes the candidates into every review addon in `addons_dirs`; how many addons took it. With no `rows` and no
    REVIEW file (a checkout without the list: data/ isn't in git), nothing is written: a list there is kept."""
    if rows is None:
        if not REVIEW.exists():
            return 0
        rows = load_review()
    text = review_lua(rows)
    n = 0
    for addons in addons_dirs:
        for folder, _sv in review_addons(addons):
            path = folder / REVIEW_FILE
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                path.write_text(text, encoding="utf-8", newline="\n")
                log(f"route review: {len(rows)} routes to check -> {path}")
            n += 1
    return n


def read_decisions(addons_dirs, rows: list | None = None) -> tuple[dict, int]:
    """The decisions in the review addons' SavedVariables (every account under each client's WTF): ({id: decision},
    how many were left out as made on another list). Read only. With `rows`, only those on a candidate there now with
    the same sig; the newest decision wins when several accounts have one."""
    from .savedvars.parser import load_savedvariables

    sigs = {str(e["id"]): sig_of(e) for e in rows} if rows else None
    found: dict = {}
    stale = 0
    for addons in addons_dirs:
        wtf = Path(addons).parent.parent / "WTF" / "Account"
        for folder, sv in review_addons(addons):
            if not sv:
                continue
            for f in sorted(wtf.glob(f"*/SavedVariables/{folder.name}.lua")):
                db = load_savedvariables(f).get(sv) or {}
                rr = db.get("routeReview") or {}
                for key, v in ((rr.get("decisions") if isinstance(rr, dict) else None) or {}).items():
                    if not isinstance(v, dict) or v.get("decision") not in DECIDED:
                        continue
                    key = str(key)
                    if sigs is not None and sigs.get(key) != v.get("sig"):
                        stale += 1
                        continue
                    at = float(v.get("at") or 0)
                    if key in found and found[key][0] > at:
                        continue
                    found[key] = (at, v)
    out = {}
    for key, (_at, v) in sorted(found.items()):
        if v["decision"] == "correct":
            tracks = v.get("tracks") or []
            if isinstance(tracks, dict):
                tracks = [tracks[k] for k in sorted(tracks)]
            out[key] = {"decision": "correct", "tracks": [int(t) for t in tracks],
                        "yd": round(float(v.get("yd") or 0)), "level": v.get("level")}
        else:
            out[key] = v["decision"]
    return out, stale


def write_decisions(decisions: dict, path: Path = DECISIONS) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(decisions, indent=1, sort_keys=True) + "\n", encoding="utf-8")
