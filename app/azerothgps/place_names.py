"""The shipped places' names in each client language (reported 2026-11-19 from a German client: in Gnomeregan's Train
Depot the inside map went and Dun Morogh's terrain showed): Data/PlaceNames/<locale>.lua, one file per language, each
read only on a client of that language.

The data's place names are the client's English ones: a model's rooms (Data/Interiors.lua's `n`, WMOAreaTable's own
names), Undercity's halls up top (Data/Cities.lua's `upper`), the buildings' and towns' spots (Data/Pois.lua's
ns.AreaSpots). The game's text is the player's language: GetMinimapZoneText() says "Zugdepot" where the data says
"Train Depot", GetBindLocation() "Taverne Zum Roten Löwen". A room's name has no id the game would look up
(C_Map.GetAreaInfo knows AreaTable's names only, and a WMOAreaTable row's own name is most of them), so they're shipped.

From wago.tools' DB2 exports of the same client build (enUS and each language, matched by row ID):
  https://wago.tools/db2/WMOAreaTable/csv?build=<build>&locale=<locale>
  https://wago.tools/db2/AreaTable/csv?build=<build>&locale=<locale>
saved as data/thirdparty/wago/<build>/<table>_<locale>.csv (never committed). itIT's are the English: none.

Kept small: only the names the data uses, and only where they differ from the English. `agps place-names` reports;
`--write` writes the files.
"""
from __future__ import annotations

import csv
import re
from collections import defaultdict
from pathlib import Path

from .paths import ADDON_DIR

OUT_DIR = ADDON_DIR / "Data" / "PlaceNames"
LOCALES = ("deDE", "esES", "esMX", "frFR", "koKR", "ptBR", "ruRU", "zhCN", "zhTW")
BUILD = "1.60.1.70959"
SOURCE = Path("thirdparty") / "wago"
TABLES = ("WMOAreaTable", "AreaTable")


def used_names(addon_dir: Path = ADDON_DIR) -> set[str]:
    """The English place names the data compares the game's text with."""
    data = addon_dir / "Data"
    names = set(re.findall(r'\bn = "([^"]+)"', (data / "Interiors.lua").read_text(encoding="utf-8")))
    for m in re.finditer(r"upper = \{([^}]*)\}", (data / "Cities.lua").read_text(encoding="utf-8")):
        names |= set(re.findall(r'\["([^"]+)"\]', m.group(1)))
    pois = (data / "Pois.lua").read_text(encoding="utf-8")
    spots = pois.split("ns.AreaSpots = {", 1)[1].split("\n}", 1)[0]
    names |= set(re.findall(r'^\s*\["([^"]+)"\] = ', spots, re.M))
    return {n for n in names if n.strip()}


def _rows(path: Path) -> dict[int, str]:
    """A table's export: { row ID: its name }."""
    with open(path, encoding="utf-8", newline="") as f:
        return {int(r["ID"]): (r["AreaName_lang"] or "").strip() for r in csv.DictReader(f)}


def build(data_dir: Path, build_id: str = BUILD, names: set[str] | None = None) -> tuple[dict, dict]:
    """{ locale: { English: [names in that language] } } (only those that differ from the English), and a report."""
    src = data_dir / SOURCE / build_id
    names = used_names() if names is None else names
    data_name = {n.strip(): n for n in names}  # (a few of the data's end in a space: the tables' don't)
    out = {loc: defaultdict(list) for loc in LOCALES}
    found = set()
    for table in TABLES:
        en = {i: data_name[n] for i, n in _rows(src / f"{table}_enUS.csv").items() if n in data_name}
        found |= set(en.values())
        for loc in LOCALES:
            local = _rows(src / f"{table}_{loc}.csv")
            for i, e in en.items():
                n = local.get(i, "")
                if n and n != e.strip() and "|" not in n and "]==]" not in n and n not in out[loc][e]:
                    out[loc][e].append(n)
    report = {"names the data uses": len(names), "in the tables": len(found),
              "not found": sorted(names - found)}
    return {loc: {e: sorted(v) for e, v in d.items()} for loc, d in out.items()}, report


def lua_text(locale: str, names: dict) -> str:
    """Data/PlaceNames/<locale>.lua: `ns.PlaceNamesLoc`, one line a place, `English|name|name...`."""
    out = ["-- GENERATED by `agps place-names --write`. Do not edit by hand.",
           f"-- The shipped places' names ({locale}): a model's rooms, Undercity's halls up top, the buildings' and towns'",
           "-- spots, as the game says them (GetMinimapZoneText, GetBindLocation), from the client's WMOAreaTable and",
           "-- AreaTable (wago.tools' exports of the same build): only where they differ from the English. Read on a",
           f"-- {locale} client only (Locales.lua's ns.ShippedPlaceNames); one line a place, English|name|name...",
           "local _, ns = ...",
           f'if not (GetLocale and GetLocale() == "{locale}") then return end',
           f'ns.PlaceNamesLocale = "{locale}"',
           "ns.PlaceNamesLoc = [==["]
    out += ["|".join([e] + names[e]) for e in sorted(names)]
    out.append("]==]")
    return "\n".join(out) + "\n"
