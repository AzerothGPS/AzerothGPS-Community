"""The heights of every NPC spawn in the capitals and in the caves (asked 2026-11-14: "all NPCs in every major city
... any path leading to those are mapped to the appropriate height ... Do this for any NPC in caves as well").

A stop with no height of its own (a guide's next stop, a /way point, a quest's) right at an NPC's spot takes that
NPC's height (Nav's N.SpawnZ), so a route to it goes to its floor where floors lie over each other: the Cleft of
Shadow under the Drag, Undercity's rings under its walkways, upstairs in Ironforge's and Stormwind's shops, a cave's
lower floor. From the CMaNGOS dump's creature spawns (hostile.py's DUMP). Heights only, as Data/GuideFloors.lua: no
names, no creature ids, nothing drawn or searched (the user, 2026-11-14: an exception to "no shipped NPC data").

Which spawns: on a continent, in a capital (its cells, Router's CapitalAt, or in its grid's rectangle within NEAR_YD
of one: the shops off Ironforge's halls, the Cenarion Enclave's tree) or in a cave (its own cells, not a capital's
nor water; on the ground over a mine too, 2026-11-14: its height over the cave's `under` keeps a stop there up on
the ground, Router's CaveDown); down in
Undercity, its own level (10001: under the ruins, UNDER_Z, over its floors). Not the ones that only fly or swim
(their height isn't a floor's). Spawns within SAME_YD and SAME_Z of one kept are left out.

`agps npc-floors` reports; `--write` writes Data/NpcFloors.lua. Run it again when the dump or the capitals' or caves'
data change.
"""
from __future__ import annotations

import gzip
import math
from pathlib import Path

from .hostile import DUMP, _rows
from .paths import ADDON_DIR

FILE = ADDON_DIR / "Data" / "NpcFloors.lua"
NEAR_YD = 20  # (in a capital's grid rectangle this near its own cells: the city's; farther out, the land round it)
UNDER_Z = 20  # (Undercity's spawns: under this, the ruins' ground over it about 60)
SAME_YD, SAME_Z = 1.0, 1.5  # (a spawn this near one kept, at about its height: the same spot)
UNDERCITY = 10001
FLY, SWIM = 4, 2  # (creature_template.InhabitType: only in the air, only in water)

_LUA = """
local ns = AGPS_NS
local R, P, N = ns.Router, ns.Passability, ns.Nav
local function nearCapital(c, x, y, r)
  if R.CapitalAt(c, x, y) then return true end
  if not P.CapitalGridAt(c, x, y) then return false end
  for d = 2, r, 2 do
    for a = 0, 15 do
      local t = a * math.pi / 8
      if R.CapitalAt(c, x + d * math.cos(t), y + d * math.sin(t)) then return true end
    end
  end
  return false
end
return function(c, x, y, z, near, underZ, uc)
  if c == 0 and z < underZ and N.CityFloor(uc, x, y) then return uc, "undercity" end
  if nearCapital(c, x, y, near) then return c, "capital" end
  local v, o = P.OverlayRaw(c, x, y)
  if v ~= nil and v ~= 1 and o and o.cave and not o.capital and not o.water then
    return c, "cave"
  end
  return nil
end
"""


def spawns(data_dir: Path) -> list[tuple]:
    """Every creature spawn on the two continents that walks: (map, x, y, z)."""
    txt = gzip.open(Path(data_dir) / DUMP, "rt", encoding="utf-8", errors="replace").read()
    inhabit = {r["Entry"]: int(r["InhabitType"] or 0) for r in _rows(txt, "creature_template")}
    out = []
    for r in _rows(txt, "creature"):
        m = int(r["map"])
        if m not in (0, 1) or inhabit.get(r["id"], 1) in (FLY, SWIM):
            continue
        out.append((m, float(r["position_x"]), float(r["position_y"]), float(r["position_z"])))
    return out


def build(data_dir: Path):
    """(entries [(level, x, y, z)], report {kind: count, "same": left out as the same spot})."""
    from .gameharness import start

    lua, _ = start({"Data/NpcFloors.lua": ""})  # (not its own output: none yet, or an old one)
    where = lua.execute(_LUA)
    kept: dict = {}  # (level, cell) -> [(x, y, z)]
    report = {"capital": 0, "undercity": 0, "cave": 0, "same": 0}
    entries = []
    for m, x, y, z in sorted(spawns(data_dir)):
        got = where(m, x, y, z, NEAR_YD, UNDER_Z, UNDERCITY)
        level, kind = got if isinstance(got, tuple) else (got, None)
        if level is None:
            continue
        x, y, z = round(x, 1), round(y, 1), round(z, 1)
        cx, cy = math.floor(x / 4), math.floor(y / 4)
        same = False
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                for px, py, pz in kept.get((level, cx + dx, cy + dy), ()):
                    same = same or (math.hypot(px - x, py - y) <= SAME_YD and abs(pz - z) <= SAME_Z)
        if same:
            report["same"] += 1
            continue
        kept.setdefault((level, cx, cy), []).append((x, y, z))
        entries.append((int(level), x, y, z))
        report[kind] += 1
    return entries, report


def lua_text(entries) -> str:
    out = ["-- GENERATED by `agps npc-floors --write` from the CMaNGOS dump's creature spawns. Do not edit by hand.",
           "-- The heights of the NPCs' spots in the capitals, down in Undercity and in the caves (the game's): heights",
           "-- only, nothing drawn or searched. Nav's N.SpawnZ: a stop with no height of its own at one takes it.",
           "-- Per level, x, y, z each.",
           "local _, ns = ...",
           "ns.NpcFloors = {"]
    by: dict = {}
    for level, x, y, z in entries:
        by.setdefault(level, []).append(f"{x:.1f},{y:.1f},{z:.1f}")
    for level in sorted(by):
        pts = by[level]
        out.append(f"  [{level}] = {{")
        for i in range(0, len(pts), 8):
            out.append("    " + ", ".join(pts[i:i + 8]) + ",")
        out.append("  },")
    out.append("}")
    return "\n".join(out) + "\n"
