"""What each shipped vendor sells, for the search (asked 2026-11-15: "need to search for all vendors items for sell to do
this correctly. Should also do this for all items so they can be searched like "arrows" or "sharp arrow" should send
me to the closest vendor that sells them"; the user chose "Both": lists shipped from data, and each vendor's real stock
learned in game when its window opens, the learned list winning: Layers' L.NoteMerchantItems).

From the CMaNGOS dump (hostile.py's DUMP): `npc_vendor` (a creature's own items) and `npc_vendor_template` (the lists
several share, by creature_template.VendorTemplateId), item names and kinds from `item_template` (English, as the
game's). Only the NPCs Data/Npcs.lua ships (`agps npcs`: the friendly and neutral ones): run `agps npcs --write`
first. An emulator's lists: a few may differ from WoW Forever's, which the in-game learning corrects.

Packed into one string (`ns.VendorItemsPacked`) read at the first search (Layers' L.VendorItems): the items first, one
line each, `id|kind|name` (kind: "a" arrows, item class 6 subclass 2; "b" bullets, subclass 3; "" anything else); a
"#" line; then one line per vendor, `npc id|its items`, each item its line's place in the list (0 the first) in base
36 split by ","; a list the same as an earlier vendor's is "=<that vendor's id>".

`agps vendors` reports; `--write` writes Data/VendorItems.lua. Run it again when the dump or Data/Npcs.lua changes.
"""
from __future__ import annotations

import gzip
from collections import defaultdict
from pathlib import Path

from .hostile import DUMP, _rows
from .paths import ADDON_DIR

FILE = ADDON_DIR / "Data" / "VendorItems.lua"
NPCS_FILE = ADDON_DIR / "Data" / "Npcs.lua"
PROJECTILE = 6  # (ItemClass)
KINDS = {(PROJECTILE, 2): "a", (PROJECTILE, 3): "b"}  # (Arrow, Bullet)
B36 = "0123456789abcdefghijklmnopqrstuvwxyz"


def b36(n: int) -> str:
    out = ""
    while True:
        n, r = divmod(n, 36)
        out = B36[r] + out
        if not n:
            return out


def shipped_npc_ids(path: Path = NPCS_FILE) -> set[int]:
    """The creature ids Data/Npcs.lua ships."""
    body = path.read_text(encoding="utf-8").split("ns.NpcsPacked = [==[", 1)[1].split("]==]", 1)[0]
    return {int(line.split("|", 1)[0]) for line in body.splitlines() if line.strip()}


def build(data_dir: Path, npc_ids: set[int] | None = None):
    """(items {id: (kind, name)}, sells {npc id: sorted item ids}) for the NPCs `npc_ids` (default: Data/Npcs.lua's)."""
    npc_ids = shipped_npc_ids() if npc_ids is None else npc_ids
    txt = gzip.open(Path(data_dir) / DUMP, "rt", encoding="utf-8", errors="replace").read()
    templates = {int(r["Entry"]): int(r.get("VendorTemplateId") or 0) for r in _rows(txt, "creature_template")}
    shared = defaultdict(set)
    for r in _rows(txt, "npc_vendor_template"):
        shared[int(r["entry"])].add(int(r["item"]))
    own = defaultdict(set)
    for r in _rows(txt, "npc_vendor"):
        own[int(r["entry"])].add(int(r["item"]))
    known = {}
    for r in _rows(txt, "item_template"):
        name = r["name"]
        if name and name != "NULL" and "|" not in name and "\n" not in name:
            known[int(r["entry"])] = (KINDS.get((int(r["class"]), int(r["subclass"])), ""), name)
    sells = {}
    for i in sorted(npc_ids):
        got = own.get(i, set()) | shared.get(templates.get(i, 0), set())
        got = sorted(x for x in got if x in known)
        if got:
            sells[i] = got
    items = {x: known[x] for x in sorted({x for s in sells.values() for x in s})}
    return items, sells


def lua_text(items: dict, sells: dict) -> str:
    place = {x: k for k, x in enumerate(sorted(items))}
    lines = [f"{x}|{items[x][0]}|{items[x][1]}" for x in sorted(items)]
    lines.append("#")
    first = {}  # (a list -> the first vendor with it)
    for i in sorted(sells):
        key = tuple(sells[i])
        if key in first:
            lines.append(f"{i}|={first[key]}")
        else:
            first[key] = i
            lines.append(f"{i}|" + ",".join(b36(place[x]) for x in key))
    body = "\n".join(lines)
    assert "]==]" not in body
    out = ["-- GENERATED by `agps vendors --write` from the CMaNGOS dump's vendor lists. Do not edit by hand.",
           "-- What each shipped vendor (Data/Npcs.lua) sells, for the search only (asked 2026-11-15): the items, one line",
           "-- each, id|kind|name (kind: a arrows, b bullets); a \"#\" line; then npc id|its items, each its line's place",
           "-- in the items (0 the first) in base 36 split by \",\", or \"=<id>\": the same list as vendor <id>'s. An",
           "-- emulator's lists: the stock learned in game wins. Read at the first search (Layers.lua's L.VendorItems).",
           "local _, ns = ...",
           "ns.VendorItemsPacked = [==[",
           body,
           "]==]"]
    return "\n".join(out) + "\n"
