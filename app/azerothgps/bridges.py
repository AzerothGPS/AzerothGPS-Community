"""The continents' bridges as outlines (addon/AzerothGPS/Data/Bridges.lua), for the directions' "Cross the bridge".

Asked 2026-11-12 for 1.2.4: "Update routing to consider say when to enter a cave or cross a bridge or go into a
building". The terrain grid can't tell a bridge (a road over a river reads as a road through water, and the marshes'
roads are that too), but the game places each bridge as a model of its own (a WMO in the ADTs whose path names it a
bridge: Thandol Span, the Crossroads' bridge, Stranglethorn's rope bridges). Each one's outline is the outline round
its floor faces (the ones a character walks on, walknet's), in world yards: Turns says "Cross the bridge" where the
walk goes over one (Router.BridgeAt). Thunder Bluff's rope bridges are part of its city models: the addon tells them
by the city's grid instead.
"""

from __future__ import annotations

import math
import re

import numpy as np

from . import interiors as I
from . import walknet
from .extract.spike import ClientData
from .paths import ADDON_DIR

FILE = ADDON_DIR / "Data" / "Bridges.lua"
NAME_RE = re.compile(r"bri?dge|brodge")  # (Desolace's rock bridge's file is "desolacerockbridge" under "rockbrodge/")
FLOOR_SLOPE = 0.7  # faces flatter than this are its floor (walknet.model_faces' slope)
MIN_FLOOR_YD2 = 20.0  # a model with less floor than this isn't walked over (a broken bridge's stub)
SIMPLIFY_YD = 0.75  # the outline's points no closer to its line than this are dropped
CONTINENTS = (0, 1)


def is_bridge(path: str) -> bool:
    """By its file's name or its folder's (Thandol Span's is "thandolspan_bridge/thandolspan.wmo")."""
    name = "/".join(path.lower().rsplit("/", 2)[-2:])
    return bool(NAME_RE.search(name)) and "broken" not in name


def outline(cd: ClientData, p) -> list[tuple[float, float]] | None:
    """A placed bridge's outline: the convex hull round its floor faces, world (X, Y), or None."""
    from scipy.spatial import ConvexHull

    try:
        floors, _walls, _liq = walknet.model_faces(cd, p.wmo, FLOOR_SLOPE)
    except Exception:
        return None
    if not floors:
        return None
    T = np.array([tri for _gi, _z, tri in floors], float).reshape(-1, 3, 3)
    xf = walknet.Placed(p)
    W = T @ xf.m.T + xf.o
    a, b, c = W[:, 0, :2], W[:, 1, :2], W[:, 2, :2]
    area = np.abs((b[:, 0] - a[:, 0]) * (c[:, 1] - a[:, 1]) - (b[:, 1] - a[:, 1]) * (c[:, 0] - a[:, 0])).sum() / 2
    if area < MIN_FLOOR_YD2:
        return None
    pts = W[:, :, :2].reshape(-1, 2)
    try:
        hull = ConvexHull(pts)
    except Exception:
        return None
    ring = [tuple(pts[i]) for i in hull.vertices]
    # (points on about a straight line between their neighbours dropped)
    changed = True
    while changed and len(ring) > 3:
        changed = False
        for i in range(len(ring)):
            (ax, ay), (bx, by), (cx, cy) = ring[i - 1], ring[i], ring[(i + 1) % len(ring)]
            L = math.hypot(cx - ax, cy - ay)
            if L > 0 and abs((cx - ax) * (by - ay) - (cy - ay) * (bx - ax)) / L < SIMPLIFY_YD:
                del ring[i]
                changed = True
                break
    return [(round(x, 1), round(y, 1)) for x, y in ring]


def bridges(cd: ClientData, cont: int, log=print) -> list[tuple[str, list]]:
    """The continent's bridges: (model name, outline), in placement order."""
    out = []
    for p in sorted(I.placements(cd, cont), key=lambda q: q.uid):
        path = cd.name(p.wmo) or ""
        if not is_bridge(path):
            continue
        ring = outline(cd, p)
        if ring is None:
            log(f"  [{cont}] {path}: no floor, left out")
            continue
        out.append((path.rsplit("/", 1)[-1].rsplit(".", 1)[0], ring))
    return out


def bridges_lua(cd: ClientData, continents=CONTINENTS, log=print) -> tuple[str, dict]:
    lines = [f"-- GENERATED by `agps bridges` (app/azerothgps/bridges.py) from client {cd.casc.version}. Do not edit by hand.",
             "-- The continents' bridges (the models placed in the ADTs that the game names bridges), each the outline round",
             "-- its floor in world yards, x, y pairs: the directions' \"Cross the bridge\" (Router.BridgeAt).",
             "local _, ns = ...",
             "ns.Bridges = {"]
    counts = {}
    for cont in continents:
        found = bridges(cd, cont, log)
        counts[cont] = len(found)
        lines.append(f"  [{cont}] = {{")
        for name, ring in found:
            pts = ",".join(f"{x:g},{y:g}" for x, y in ring)
            lines.append(f"    {{ {pts} }}, -- {name}")
        lines.append("  },")
    lines.append("}")
    return "\n".join(lines) + "\n", counts
