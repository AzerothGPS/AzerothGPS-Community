"""Who takes each quest in, for the quest route's turn-in stops (Kooki3z, 2026-11-22: a turn-in stop at the quest
marker's map spot ended outside the NPC's building, its NPC upstairs; now it's put at the NPC's spawn, with its height
and the Target button).

From the CMaNGOS dump (hostile.py's DUMP): creature_involvedrelation, each quest's enders, only those shipped in
Data/Npcs.lua (`agps npcs`: their spawns are the stops' spots). Numbers only: `quest ender,ender` a line, one string
(`ns.QuestEndersPacked`), read at the first quest turn-in stop (Layers.lua's `Lay.QuestEnders`).

`agps quest-npcs` reports; `--write` writes Data/QuestNpcs.lua. Run it again when the dump or Data/Npcs.lua changes.
"""
from __future__ import annotations

import gzip
import re
from collections import defaultdict
from pathlib import Path

from .hostile import DUMP, _rows
from .paths import ADDON_DIR

FILE = ADDON_DIR / "Data" / "QuestNpcs.lua"
NPCS = ADDON_DIR / "Data" / "Npcs.lua"


def shipped_ids(npcs_lua: Path = NPCS) -> set[int]:
    """The creature ids Data/Npcs.lua ships."""
    return {int(m) for m in re.findall(r"^(\d+)\|", npcs_lua.read_text(encoding="utf-8"), re.M)}


def build(data_dir: Path, ids: set[int] | None = None) -> dict[int, list[int]]:
    """{quest: [ender creature ids]}, shipped NPCs only."""
    ids = shipped_ids() if ids is None else ids
    txt = gzip.open(Path(data_dir) / DUMP, "rt", encoding="utf-8", errors="replace").read()
    out: dict[int, set[int]] = defaultdict(set)
    for r in _rows(txt, "creature_involvedrelation"):
        npc, quest = int(r["id"]), int(r["quest"])
        if npc in ids:
            out[quest].add(npc)
    return {q: sorted(v) for q, v in out.items()}


def lua_text(enders: dict[int, list[int]]) -> str:
    body = "\n".join(f"{q} {','.join(str(i) for i in enders[q])}" for q in sorted(enders))
    out = ["-- GENERATED by `agps quest-npcs --write` from the CMaNGOS dump's creature_involvedrelation. Do not edit by",
           "-- hand. Who takes each quest in (numbers only): \"quest npc,npc\" a line, the NPCs' creature ids, only those",
           "-- in Data/Npcs.lua. A quest route's turn-in stop goes to that NPC's spawn (Layers.lua's Lay.AtQuestNpc).",
           "local _, ns = ...",
           "ns.QuestEndersPacked = [==[",
           body,
           "]==]"]
    return "\n".join(out) + "\n"
